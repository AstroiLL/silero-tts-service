#!/usr/bin/env python3
"""Латиница → кириллица для русского Silero TTS.

Русская модель Silero полностью ВЫБРАСЫВАЕТ латинские слова (проверено:
фраза с шестью английскими терминами дала 1.7 с вместо ~8 с). Поэтому любое
латинское слово нужно переписать кириллицей до синтеза.

Порядок разрешения (см. prepare_text в silero_tts.py):
    1. lexicon.json — ручные правила, всегда главнее;
    2. ABBREVIATIONS — известные аббревиатуры читаются как слово или по буквам;
    3. ALL-CAPS длиной 2..5 — по названиям английских букв (API → эй-пи-ай);
    4. всё остальное — транслитерация по правилам чтения (биграммы/триграммы).

Транслитерация грубая: цель — разборчивость, а не фонетическая точность.
Слово, которое звучит заметно криво, заносится в lexicon.json через lexicon.py.
"""
from __future__ import annotations

import re

# Названия английских букв по-русски — для побуквенного чтения аббревиатур.
LETTERS = {
    "a": "эй", "b": "би", "c": "си", "d": "ди", "e": "и", "f": "эф", "g": "джи",
    "h": "эйч", "i": "ай", "j": "джей", "k": "кей", "l": "эл", "m": "эм",
    "n": "эн", "o": "оу", "p": "пи", "q": "кью", "r": "ар", "s": "эс",
    "t": "ти", "u": "ю", "v": "ви", "w": "дабл-ю", "x": "экс", "y": "уай",
    "z": "зед",
}

# Аббревиатуры, которые читаются не по буквам или имеют устоявшееся звучание.
ABBREVIATIONS = {
    "api": "ап+и", "url": "ю-эр-+эл", "ui": "юз+ер интерф+ейс", "ux": "ю-+экс",
    "cpu": "си-пи-ю", "gpu": "джи-пи-ю", "ram": "р+ам", "ssd": "эс-эс-д+и",
    "hdd": "эйч-ди-д+и", "usb": "ю-эс-б+и", "ssh": "эс-эс-+эйч",
    "html": "эйч-ти-эм-+эл", "css": "си-эс-+эс", "sql": "эс-кью-+эл",
    "json": "джейс+он", "yaml": "ям+л", "csv": "си-эс-в+и",
    "llm": "эл-эл-+эм", "ai": "а+и", "ml": "эм-+эл", "tts": "ти-ти-+эс",
    "stt": "эс-ти-+ти", "asr": "эй-эс-+ар", "sdk": "эс-ди-к+ей",
    "ide": "ай-ди-+и", "os": "оу-+эс", "io": "ай-+оу", "ip": "ай-п+и",
    "dns": "ди-эн-+эс", "vpn": "ви-пи-+эн", "lan": "л+ан", "wifi": "вай-ф+ай",
    "mcp": "эм-си-п+и", "cli": "си-эл-+ай", "gui": "г+уи", "ok": "ок+ей",
    "pdf": "пи-ди-+эф", "png": "пи-эн-дж+и", "jpg": "джей-пи-дж+и",
    "mp3": "эм-пи-тр+и", "http": "эйч-ти-ти-п+и", "https": "эйч-ти-ти-пи-+эс",
    "ftp": "эф-ти-п+и", "smtp": "эс-эм-ти-п+и", "rest": "р+ест",
    "crud": "кр+уд", "git": "гит", "npm": "эн-пи-+эм", "pip": "пип",
}

# Правила чтения: сначала длинные сочетания, потом короткие.
# Порядок внутри списка значим — применяется первое совпадение.
RULES: list[tuple[str, str]] = [
    ("tion", "шн"), ("sion", "жн"), ("ough", "оу"), ("ight", "айт"),
    ("augh", "аф"),
    ("tch", "ч"), ("sch", "ск"), ("thr", "тр"), ("shr", "шр"),
    ("ing", "инг"), ("age", "идж"), ("ure", "ур"), ("ous", "ас"),
    ("our", "ор"), ("ture", "чер"),
    ("ce", "с"), ("ci", "си"), ("cy", "си"),
    ("ch", "ч"), ("sh", "ш"), ("th", "з"), ("ph", "ф"), ("wh", "в"),
    ("ck", "к"), ("qu", "кв"), ("kn", "н"), ("wr", "р"), ("gh", "г"),
    ("ng", "нг"), ("ll", "л"), ("ss", "с"), ("tt", "т"), ("pp", "п"),
    ("ff", "ф"), ("mm", "м"), ("nn", "н"), ("rr", "р"), ("dd", "д"),
    ("cc", "к"), ("bb", "б"), ("gg", "г"),
    ("ee", "и"), ("ea", "и"), ("oo", "у"), ("ou", "ау"), ("ow", "ау"),
    ("oa", "оу"), ("ai", "эй"), ("ay", "эй"), ("ey", "эй"), ("ie", "и"),
    ("oi", "ой"), ("oy", "ой"), ("au", "о"), ("aw", "о"), ("ew", "ю"),
    ("ue", "у"), ("ui", "уи"),
    ("ar", "ар"), ("er", "ер"), ("ir", "ир"), ("or", "ор"), ("ur", "ур"),
    ("a", "а"), ("b", "б"), ("c", "к"), ("d", "д"), ("e", "е"), ("f", "ф"),
    ("g", "г"), ("h", "х"), ("i", "и"), ("j", "дж"), ("k", "к"), ("l", "л"),
    ("m", "м"), ("n", "н"), ("o", "о"), ("p", "п"), ("q", "к"), ("r", "р"),
    ("s", "с"), ("t", "т"), ("u", "у"), ("v", "в"), ("w", "в"), ("x", "кс"),
    ("y", "и"), ("z", "з"),
]

_MAX_RULE = max(len(src) for src, _ in RULES)
_RULE_MAP = {src: dst for src, dst in RULES}
_LATIN_WORD = re.compile(r"[A-Za-z][A-Za-z0-9'’-]*")


def spell_letters(word: str) -> str:
    """API -> 'эй-пи-ай'. Цифры читаются как есть."""
    parts = [LETTERS.get(ch.lower(), ch) for ch in word if ch.isalnum()]
    return "-".join(parts)


def transliterate(word: str) -> str:
    """Побуквенно-пословная транслитерация по правилам чтения."""
    low = word.lower()
    out: list[str] = []
    i = 0
    while i < len(low):
        if not low[i].isalpha():
            out.append(low[i])
            i += 1
            continue
        for size in range(_MAX_RULE, 0, -1):
            chunk = low[i:i + size]
            if chunk in _RULE_MAP:
                out.append(_RULE_MAP[chunk])
                i += size
                break
        else:
            i += 1
    # Немая конечная "e" в английском: "code" -> "коде" -> "код".
    result = "".join(out)
    if len(result) > 2 and low.endswith("e") and not low.endswith(("ee", "ie", "oe")):
        result = result[:-1]
    return result


def convert_word(word: str) -> str:
    low = word.lower()
    if low in ABBREVIATIONS:
        return ABBREVIATIONS[low]
    if word.isupper() and 2 <= len(word) <= 5:
        return spell_letters(word)
    return transliterate(word)


def convert_text(text: str) -> str:
    """Переписать все латинские слова кириллицей."""
    return _LATIN_WORD.sub(lambda m: convert_word(m.group(0)), text)


if __name__ == "__main__":
    import sys
    print(convert_text(" ".join(sys.argv[1:]) or sys.stdin.read()))
